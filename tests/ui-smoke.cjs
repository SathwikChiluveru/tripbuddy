/* Run against an explicitly seeded local preview; fixtures are removed afterward. */
const { chromium } = require('../client/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const base = process.env.UI_BASE || 'http://localhost:5173';
const stamp = Date.now();
const errors = [];
let userId;
let context;
let browser;
async function main() {
  const executablePath = process.env.BROWSER_PATH || (process.platform === 'win32' ? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' : undefined);
  browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
  context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const output = path.join(root, '.local/ui'); await fs.mkdir(output, { recursive: true });
  await page.goto(base); await page.getByRole('heading', { name: /Good places/ }).waitFor();
  await page.locator('article').first().waitFor();
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile layout must not overflow');
  assert.equal(await page.getByRole('link', { name: 'Sign in', exact: true }).isVisible(), true, 'mobile sign-in stays visible without opening the menu');
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('link', { name: 'Explore trips', exact: true }).click();
  await page.getByRole('heading', { name: 'Where to next?' }).waitFor();
  assert.equal(await page.evaluate(() => document.activeElement.tagName), 'MAIN', 'route navigation moves focus to the new main content');
  assert.ok(await page.evaluate(() => [...document.querySelectorAll('.filter-tabs button')].every(button => button.getBoundingClientRect().height >= 44)), 'mobile category filters meet the 44px touch target');
  await page.getByRole('textbox', { name: 'Search trips' }).fill('NoDestinationHasThisName');
  await page.getByRole('heading', { name: 'A little off the beaten path.' }).waitFor();
  await page.setViewportSize({ width: 1440, height: 1000 });
  const email = `preview${stamp}@example.com`, password = 'PreviewOnly2026!';
  const registration = await context.request.post(base + '/api/user/register', { data: { firstName: 'Preview', lastName: 'Tester', username: `preview${stamp}`, email, password } });
  assert.equal(registration.status(), 201); userId = (await registration.json()).user._id;
  const signIn = await context.request.post(base + '/api/auth/login', { data: { email, password } }); assert.equal(signIn.status(), 200);
  await page.goto(base + '/createtrip');
  await page.getByRole('heading', { name: 'Make a little adventure.' }).waitFor();
  await page.getByRole('button', { name: 'Sign out' }).waitFor();
  const me = await context.request.get(base + '/api/auth/me'); assert.equal(me.status(), 200); userId = (await me.json())._id;
  await page.goto(base + '/createtrip');
  await page.getByLabel('Give your trip a name').fill(`Disposable preview journey ${stamp}`);
  assert.ok(await page.locator('#trip-countries option').count() >= 40, 'country autocomplete provides a broad bundled destination list');
  await page.getByLabel('Country', { exact: true }).fill('Portugal');
  assert.equal(await page.locator('#trip-cities option').count(), 10, 'city suggestions update to the selected country');
  await page.getByLabel('City or region').fill('Lagos');
  await page.getByLabel('Start date', { exact: true }).fill('2027-04-01');
  await page.getByLabel('End date', { exact: true }).fill('2027-04-06');
  await page.getByLabel('Travel style (optional, comma separated)').fill('Nature, Beach');
  await page.getByLabel('Tell your future buddies about the trip').fill('Disposable automated browser test of the complete trip publishing flow.');
  assert.equal(await page.getByLabel('Tell your future buddies about the trip').getAttribute('required'), null, 'trip story is optional');
  await page.getByLabel('Country', { exact: true }).fill('Atlantis');
  await page.getByLabel('City or region').fill('Atlantis');
  await page.getByRole('button', { name: 'Publish your trip' }).click();
  await page.getByRole('alert').getByText('Choose a country from the suggestions so we can verify the destination.').waitFor();
  await page.getByLabel('Country', { exact: true }).fill('Portugal');
  await page.getByLabel('City or region').fill('Made-up Town');
  await page.getByRole('button', { name: 'Publish your trip' }).click();
  await page.getByRole('alert').getByText('Choose a city listed for Portugal.').waitFor();
  await page.getByLabel('City or region').fill('Lagos');
  await page.getByRole('button', { name: 'Publish your trip' }).click();
  await page.getByRole('heading', { name: `Disposable preview journey ${stamp}`, exact: true }).waitFor();
  await page.getByRole('button', { name: 'Edit trip', exact: true }).click();
  await page.getByLabel('Give your trip a name').fill(`Updated preview journey ${stamp}`);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('heading', { name: `Updated preview journey ${stamp}`, exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'trip-detail.png'), fullPage: true });
  const tripUrl = page.url();
  await page.getByRole('link', { name: 'My trips', exact: true }).click();
  await page.getByRole('heading', { name: 'Trips you host' }).waitFor();
  await page.getByText(`Updated preview journey ${stamp}`, { exact: true }).waitFor();
  await page.goto(tripUrl);
  await page.getByRole('heading', { name: `Updated preview journey ${stamp}`, exact: true }).waitFor();
  await page.getByRole('link', { name: 'Open group chat' }).click();
  const selectedConversation = page.getByRole('button', { name: new RegExp(`Updated preview journey ${stamp}`) });
  await selectedConversation.waitFor();
  await page.waitForFunction(() => document.querySelector('.chat-list button.active') !== null);
  assert.equal(await selectedConversation.getAttribute('aria-pressed'), 'true', 'trip detail chat link opens the matching conversation');
  await page.getByRole('link', { name: 'Trip details' }).waitFor();
  await page.getByLabel('Your message').fill('Hello from the browser smoke test.');
  await page.getByRole('button', { name: 'Send message' }).click();
  await page.getByText('Hello from the browser smoke test.', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'chat.png'), fullPage: true });
  await page.goto(base + '/editprofile');
  await page.getByLabel('About you').fill('Profile updated through the real browser UI.');
  await page.getByLabel('Countries you’ve visited (comma separated)').fill('Portugal, Singapore');
  await page.getByRole('button', { name: 'Save profile' }).click();
  await page.getByText('Profile updated through the real browser UI.', { exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Your world so far' }).waitFor();
  await page.getByText('Portugal', { exact: true }).waitFor();
  await page.getByText('Singapore', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'profile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByRole('link', { name: 'Sign in', exact: true }).waitFor();
  assert.equal((await context.request.get(base + '/api/auth/me')).status(), 401);
  // Restore the disposable user's session only to remove the test fixtures.
  const login = await context.request.post(base + '/api/auth/login', { data: { email, password } });
  assert.equal(login.status(), 200);
  assert.deepEqual(errors, []);
  console.log('UI smoke passed: desktop/mobile, discovery empty state, protected route, trip create/edit, chat, profile save, and Google-only sign-in screen/logout. A disposable test user is provisioned via the legacy compatibility API.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (userId && context) {
    const res = await context.request.delete(base + `/api/user/${userId}`).catch(() => null);
    if (!res?.ok()) console.error('Disposable fixture cleanup failed for', userId);
  }
  await browser?.close();
});
